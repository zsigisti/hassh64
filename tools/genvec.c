#include <stdio.h>
#include "../hassh.h"
static const size_t extra[] = {511, 512, 513, 1000, 4095, 4096, 4097, 4224, 4225, 4300, 8192, 12345, 20000};
#define NEXTRA (sizeof extra / sizeof extra[0])
int main(void) {
    static uint8_t m[20000];
    for (size_t i = 0; i < sizeof m; i++) m[i] = (uint8_t)(i * 31 + 7);
    const uint64_t seeds[2] = {0, 0x0123456789abcdefull};
    printf("/* hassh64 2.x known-answer vectors. GENERATED by tools/genvec.c; do not edit.\n"
           " * Message: byte i = (i * 31 + 7) mod 256, first len bytes.\n"
           " * Any change to these values is a new major version. */\n"
           "static const struct { unsigned len; unsigned long long seed, hash; } HASSH_VECTORS[] = {\n");
    for (int s = 0; s < 2; s++) {
        for (size_t l = 0; l <= 260; l++)
            printf("    {%zu, 0x%016llxull, 0x%016llxull},\n", l, (unsigned long long)seeds[s], (unsigned long long)hassh64(m, l, seeds[s]));
        for (size_t k = 0; k < NEXTRA; k++)
            printf("    {%zu, 0x%016llxull, 0x%016llxull},\n", extra[k], (unsigned long long)seeds[s], (unsigned long long)hassh64(m, extra[k], seeds[s]));
    }
    printf("};\n");
}
